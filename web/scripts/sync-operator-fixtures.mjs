// Rewrites src/test/operator-fixtures.ts so it lists every file in
// ../fixtures/contract/operator (captured by the mock chain) and
// ../fixtures/contract/operator/golden (written by the operator's Rust test).
//
//   npm run fixtures:sync
//
// Explicit imports are used because `import.meta` is banned outside
// src/lib/config.ts (so no import.meta.glob). The tests prove the list is
// complete (they compare it with each folder's index.json), so a new fixture
// that was not synced fails a test rather than going unchecked.

import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const WEB = process.cwd();
const ROOT = resolve(WEB, "../fixtures/contract/operator");
const OUT = resolve(WEB, "src/test/operator-fixtures.ts");
const REL = "../../../fixtures/contract/operator";

const names = (dir, test) => readdirSync(dir, { withFileTypes: true }).filter((e) => e.isFile() && test(e.name)).map((e) => e.name).sort();
const ident = (prefix, name) => `${prefix}_${name.replace(/\.(json|csv|sse\.txt)$/u, "").replace(/[^a-z0-9]/gu, "_")}`;
const importLine = (id, path) => `import ${id} from "${REL}/${path}?raw";`;

const captured = names(ROOT, (n) => (n.endsWith(".json") && n !== "index.json") || n.endsWith(".sse.txt"));
const csv = names(join(ROOT, "csv"), (n) => n.endsWith(".csv"));
const golden = names(join(ROOT, "golden"), (n) => n.endsWith(".json") && n !== "index.json");

const map = (prefix, files, folder = "") =>
  files.map((n) => `  "${n}": ${ident(prefix, folder === "csv" ? `${n.replace(/\.csv$/u, "")}_csv.csv` : n)},`).join("\n");

const imports = [
  ...captured.map((n) => importLine(ident("f", n), n)),
  importLine("indexText", "index.json"),
  ...csv.map((n) => importLine(ident("f", `${n.replace(/\.csv$/u, "")}_csv.csv`), `csv/${n}`)),
  importLine("goldenIndexText", "golden/index.json"),
  ...golden.map((n) => importLine(ident("g", n), `golden/${n}`)),
].join("\n");

const text = `// GENERATED by scripts/sync-operator-fixtures.mjs (npm run fixtures:sync). Do not edit by hand.
//
// Every operator fixture, loaded as text. Explicit imports (not import.meta.glob,
// which is banned outside lib/config.ts) so each file is visible here. The tests
// prove this list is complete against each folder's index.json, so adding a
// fixture without syncing fails a test instead of going unchecked.
//
// The captures are rewritten by: node scripts/capture-operator-fixtures.mjs
// The golden/ files are written by the operator's own Rust test.

${imports}

/** Response files by name (e.g. "create-valid.json"), as text. */
export const FIXTURES: Readonly<Record<string, string>> = {
${map("f", captured)}
};

/** The sentinel CSV inputs by name (e.g. "valid.csv"). */
export const CSV: Readonly<Record<string, string>> = {
${map("f", csv, "csv")}
};

export const INDEX_TEXT = indexText;

export interface IndexEntry {
  file: string;
  method: string;
  path: string;
  status: number;
  note: string;
  request?: { csv: string; name: string; max_outputs_per_batch: number; fee_policy: string };
}

/** index.json: every response file with the request that produced it. */
export const INDEX: readonly IndexEntry[] = (JSON.parse(indexText) as { files: IndexEntry[] }).files;

/** A response body parsed from JSON. Throws if the fixture is missing. */
export function fixtureJson(name: string): unknown {
  const text = FIXTURES[name];
  if (text === undefined) throw new Error(\`no operator fixture named \${name}\`);
  return JSON.parse(text);
}

// ---- golden/: real-chain shapes written by the operator's own Rust test ---------------
//
// crates/drop-operator/tests/api_contract.rs writes these (the real handlers over
// an in-memory real-chain backend). The capture script never touches them.

/** golden/*.json by file name (without the folder). */
export const GOLDEN: Readonly<Record<string, string>> = {
${map("g", golden)}
};

export interface GoldenEntry {
  file: string;
  method: string;
  path: string;
  status: number;
  note: string;
}

export const GOLDEN_INDEX: readonly GoldenEntry[] = (JSON.parse(goldenIndexText) as { files: GoldenEntry[] }).files;

/** A golden response parsed from JSON. Throws if there is no such file. */
export function goldenJson(name: string): unknown {
  const text = GOLDEN[name];
  if (text === undefined) throw new Error(\`no golden operator fixture named \${name}\`);
  return JSON.parse(text);
}
`;

writeFileSync(OUT, text);
console.log(`wrote ${OUT}: ${String(captured.length)} captured, ${String(csv.length)} csv, ${String(golden.length)} golden`);
