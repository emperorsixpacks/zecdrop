// The PUBLIC receipt, as served by the key-less verifier.
//
// Two layers:
//   wire   what actually travels: the Rust serde output (crates/drop-core
//          receipt.rs), snake_case, validated here with strict zod schemas;
//   view   what UI code uses: camelCase, with the outpoint parsed and the
//          phase as a discriminated union. parsePublicReceipt() is the only
//          way from the first to the second.
//
// Rules this file enforces at runtime:
//   1. Every object is `.strict()`, mirroring the core's `deny_unknown_fields`.
//      A payload carrying `recipients`, `address`, `amount`, `memo` (or
//      anything else unknown) is REJECTED, never stripped: a verifier that
//      starts leaking those fields must fail loudly here (REQ-PRIV-001).
//   2. Amounts are decimal strings of zatoshi, at most the 21M ZEC supply.
//      u64 does not fit a JS number, and the core refuses larger values.
//   3. Ids are lowercase hex of exact length, so they are also safe to put in
//      an explorer URL.
//   4. A `null` fact means "the verifier could not establish it", and the
//      reason is in `findings`. Null is part of the contract, not an error.
//
// Golden files generated by the Rust tests (fixtures/contract/public-receipt*
// .json) are parsed in contract.test.ts. If the wire format moves, the Rust
// test fails until the fixtures are regenerated, which fails that test until
// this file is updated: neither side can drift alone.

import { z } from "zod";

import type { PhaseState } from "@/lib/phase";
import { isMoneyZatoshiString } from "@/lib/zec";

import { findingWire, type ReceiptFinding } from "./findings";

// ---- View types (what the UI sees) ---------------------------------------

export const RECEIPT_POOLS = ["ironwood", "orchard"] as const;
export type ReceiptPool = (typeof RECEIPT_POOLS)[number];

export interface OutPointView {
  /** Funding transaction id: 64 lowercase hex characters. */
  txid: string;
  /** Output index within that transaction. */
  vout: number;
}

/** Facts about one batch. Every `null` was not established; see `findings`. */
export interface PublicReceiptBatch {
  index: number;
  /** Null until the batch transaction has been built. */
  txid: string | null;
  /** The transparent output this batch spends. */
  fundingInput: OutPointView | null;
  /** Zatoshi, decimal string: the value entering the shielded pool. */
  netIntoPool: string | null;
  /** Zatoshi, decimal string. */
  fee: string | null;
  /** Shielded actions in the transaction (about the recipient count). */
  shieldedActions: number | null;
  pool: ReceiptPool | null;
  confirmations: number;
}

export interface PublicReceipt {
  /** Null when the verifier was not told which campaign this is. */
  campaignId: string | null;
  network: "testnet" | "mainnet";
  /** The one transparent address every batch spends from, public on the chain;
   * null when the verifier did not establish it. Together with the manifest
   * commitment this is what ties a receipt to a campaign. */
  fundingAddress: string | null;
  /** Zatoshi, decimal string: the total the campaign DECLARES. */
  declaredTotal: string;
  /** Zatoshi, decimal string; null unless every batch's fee is known. */
  feeTotal: string | null;
  /** 64 lowercase hex characters. */
  manifestCommitment: string;
  phase: PhaseState;
  batches: PublicReceiptBatch[];
  /** Problems the verifier found; empty when everything checks out. */
  findings: ReceiptFinding[];
}

// ---- Wire schemas (what the verifier sends) ------------------------------

const U32_MAX = 4_294_967_295;
const u32 = z.number().int().min(0).max(U32_MAX);

/** 32 bytes as lowercase hex: txids and the manifest commitment. */
const hex32 = z
  .string()
  .regex(/^[0-9a-f]{64}$/u, "must be 64 lowercase hex characters");

const zatoshi = z.string().refine(isMoneyZatoshiString, {
  message: "must be a whole number of zatoshi, at most the 21M ZEC supply",
});

const OUTPOINT = /^([0-9a-f]{64}):(0|[1-9][0-9]{0,9})$/u;

/** "<txid>:<vout>" on the wire, a parsed {txid, vout} in the view. */
const outPoint = z.string().transform((text, ctx): OutPointView => {
  const match = OUTPOINT.exec(text);
  const vout = match ? Number(match[2]) : Number.NaN;
  if (!match || !(vout <= U32_MAX)) {
    ctx.addIssue({ code: "custom", message: 'must look like "<64 hex>:<index>"' });
    return z.NEVER;
  }
  return { txid: match[1] as string, vout };
});

const batchWire = z
  .object({
    index: u32,
    txid: hex32.nullable(),
    funding_input: outPoint.nullable(),
    net_into_pool: zatoshi.nullable(),
    fee: zatoshi.nullable(),
    shielded_actions: u32.nullable(),
    pool: z.enum(RECEIPT_POOLS).nullable(),
    confirmations: u32,
  })
  .strict()
  .transform(
    (b): PublicReceiptBatch => ({
      index: b.index,
      txid: b.txid,
      fundingInput: b.funding_input,
      netIntoPool: b.net_into_pool,
      fee: b.fee,
      shieldedActions: b.shielded_actions,
      pool: b.pool,
      confirmations: b.confirmations,
    }),
  );

// Internally tagged, like the core's `#[serde(tag = "phase")]`. Each variant
// is strict, so `{"phase":"settled","done":1}` is refused.
const phaseWire = z.discriminatedUnion("phase", [
  z.object({ phase: z.literal("draft") }).strict(),
  z.object({ phase: z.literal("awaiting_funding") }).strict(),
  z.object({ phase: z.literal("funded") }).strict(),
  z
    .object({ phase: z.literal("sending"), done: u32, total: u32 })
    .strict()
    .refine((p) => p.done <= p.total, { message: "done cannot exceed total" }),
  z.object({ phase: z.literal("settled") }).strict(),
  z.object({ phase: z.literal("failed") }).strict(),
]);

const receiptWire = z
  .object({
    campaign_id: z
      .string()
      .regex(/^[A-Za-z0-9._-]{1,64}$/u, "invalid campaign id")
      .nullable(),
    network: z.enum(["testnet", "mainnet"]),
    // The one transparent address every batch spends from, or null when the
    // verifier could not establish it. Required: every receipt the core produces
    // carries the key, so a receipt without it is not one of ours.
    funding_address: z.string().min(1).max(512).regex(/^\S+$/u, "address contains whitespace").nullable(),
    declared_total: zatoshi,
    fee_total: zatoshi.nullable(),
    batches: z.array(batchWire).max(10_000),
    manifest_commitment: hex32,
    phase: phaseWire,
    findings: z.array(findingWire).max(10_000),
  })
  .strict()
  .transform(
    (r): PublicReceipt => ({
      campaignId: r.campaign_id,
      network: r.network,
      fundingAddress: r.funding_address,
      declaredTotal: r.declared_total,
      feeTotal: r.fee_total,
      manifestCommitment: r.manifest_commitment,
      phase: r.phase,
      batches: r.batches,
      findings: r.findings,
    }),
  );

/** Validate untrusted JSON as a public receipt and map it to the view type.
 * Throws ZodError on any deviation, including unknown (e.g. per-recipient)
 * fields. Error messages name offending keys and rules, never the values. */
export function parsePublicReceipt(input: unknown): PublicReceipt {
  return receiptWire.parse(input);
}

// Building blocks shared with the operator API schemas (src/api/operator), so
// a txid, an outpoint, an amount or a phase is validated by ONE definition.
export {
  hex32 as hex32Wire,
  outPoint as outPointWire,
  phaseWire,
  u32 as u32Wire,
  zatoshi as zatoshiWire,
};
